#!/usr/bin/env bash
# Usage: build.sh [--dev] [crate ...]
#   --dev     unoptimised wasm-pack --dev build (wasm-opt not required)
#   crate     build only these crates (directory names under crates/);
#             default is every crate except `shared`
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WORKSPACE_DIR="$(dirname "$SCRIPT_DIR")"
PKG_DIR="$WORKSPACE_DIR/pkg"

# Ensure Rust toolchain binaries are on PATH
RUSTUP_HOME="${RUSTUP_HOME:-$HOME/.rustup}"
CARGO_HOME="${CARGO_HOME:-$HOME/.cargo}"
TOOLCHAIN_BIN="$RUSTUP_HOME/toolchains/stable-$(rustc -vV 2>/dev/null | grep host | awk '{print $2}' || echo 'aarch64-apple-darwin')/bin"
export PATH="$CARGO_HOME/bin:$TOOLCHAIN_BIN:$PATH"

# Parse args
PROFILE="release"
CRATES=()
for arg in "$@"; do
  case "$arg" in
    --dev) PROFILE="dev" ;;
    -*) echo "Unknown option: $arg" >&2; exit 2 ;;
    *) CRATES+=("$arg") ;;
  esac
done

WASM_PACK_MODE="--release"
if [[ "$PROFILE" == "dev" ]]; then
  WASM_PACK_MODE="--dev"
fi

# Release output must be wasm-opt'd: without it pdf_bg.wasm alone grows past
# Cloudflare Pages' 25 MiB per-file limit. Fail before spending minutes on
# cargo rather than silently shipping unoptimised wasm.
if [[ "$PROFILE" == "release" ]] && ! command -v wasm-opt &>/dev/null; then
  cat >&2 <<'EOF'
error: wasm-opt (binaryen) not found on PATH; release WASM builds require it.
  macOS:          brew install binaryen
  Debian/Ubuntu:  sudo apt-get install -y binaryen
  other:          https://github.com/WebAssembly/binaryen/releases
Use `--dev` for an unoptimised build without wasm-opt.
EOF
  exit 1
fi

if [[ ${#CRATES[@]} -eq 0 ]]; then
  for crate_dir in "$WORKSPACE_DIR"/crates/*/; do
    crate_name=$(basename "$crate_dir")
    # Skip shared (it's a library, not a wasm target)
    [[ "$crate_name" == "shared" ]] && continue
    CRATES+=("$crate_name")
  done
fi

echo "Building WASM crates ($PROFILE): ${CRATES[*]}"

for crate_name in "${CRATES[@]}"; do
  crate_dir="$WORKSPACE_DIR/crates/$crate_name"
  if [[ ! -d "$crate_dir" || "$crate_name" == "shared" ]]; then
    echo "error: '$crate_name' is not a buildable crate under $WORKSPACE_DIR/crates" >&2
    exit 2
  fi

  echo "  Building $crate_name..."
  wasm-pack build "$crate_dir" \
    --target web \
    $WASM_PACK_MODE \
    --out-dir "$PKG_DIR/$crate_name" \
    --out-name "$crate_name"

  # Remove unnecessary files generated by wasm-pack
  rm -f "$PKG_DIR/$crate_name/.gitignore"
  rm -f "$PKG_DIR/$crate_name/package.json"

  if [[ "$PROFILE" == "release" ]]; then
    wasm_file="$PKG_DIR/$crate_name/${crate_name}_bg.wasm"
    echo "  Optimizing $(basename "$wasm_file") with wasm-opt..."
    wasm-opt -Oz --strip-debug "$wasm_file" -o "$wasm_file"
  fi
done

echo "Done. Output in $PKG_DIR/"
