// Renders `crates/registry/src/generated.rs` from the resolved Tool routes
// (ADR-0035 §6). Pure, so the spec can feed it routes; the writer is
// generate-registry.ts.
import type { ToolCategory, ToolLayout, ToolRoute } from '../../src/types/constants/tool-registry'

// Typed as records so a new category or layout in tool-routes.ts fails the
// typecheck until it has a Rust variant here.
const CATEGORY_VARIANTS: Record<ToolCategory, string> = {
  Code: 'Code',
  Color: 'Color',
  CSS: 'Css',
  Data: 'Data',
  Encoding: 'Encoding',
  Generator: 'Generator',
  Image: 'Image',
  Network: 'Network',
  Security: 'Security',
  Text: 'Text',
  Time: 'Time',
  Unit: 'Unit',
}

const LAYOUT_VARIANTS: Record<ToolLayout, string> = {
  codec: 'Codec',
  comparator: 'Comparator',
  custom: 'Custom',
  'file-processor': 'FileProcessor',
  generator: 'Generator',
  transformer: 'Transformer',
}

const KEY_SHAPE = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/

const HEADER = `//! Generated by \`scripts/dioxus/generate-registry.ts\` from
//! \`src/constants/tool-routes.ts\` (ADR-0035 §6). Do not edit it: change
//! \`tool-routes.ts\`, then run \`node scripts/dioxus/generate-registry.ts\`.
//! CI fails if regenerating it leaves a diff.

use crate::{Seo, Tool};
`

const DERIVE = '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]'

// A Rust string literal. JSON's escapes are not all valid Rust (`\uXXXX`).
const rustString = (value: string): string => {
  let escaped = ''
  for (const char of value) {
    const code = char.codePointAt(0) ?? 0
    if (char === '\\' || char === '"') escaped += `\\${char}`
    else if (code < 0x20 || code === 0x7f) escaped += `\\u{${code.toString(16)}}`
    else escaped += char
  }
  return `"${escaped}"`
}

const variantOf = (key: string): string => {
  if (!KEY_SHAPE.test(key)) {
    throw new Error(`Tool key ${JSON.stringify(key)} is not lower-case words joined by hyphens`)
  }
  return key
    .split('-')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join('')
}

const renderEnum = (doc: string, name: string, variants: Array<string>): string =>
  [`/// ${doc}`, DERIVE, `pub enum ${name} {`, ...variants.map((variant) => `    ${variant},`), '}'].join('\n')

const renderAsStr = (name: string, values: Record<string, string>): string =>
  [
    `impl ${name} {`,
    '    /// The value as `tool-routes.ts` spells it.',
    "    pub fn as_str(self) -> &'static str {",
    '        match self {',
    ...Object.entries(values).map(([value, variant]) => `            Self::${variant} => ${rustString(value)},`),
    '        }',
    '    }',
    '}',
  ].join('\n')

const renderTool = (route: ToolRoute): string =>
  [
    '    Tool {',
    `        key: ToolKey::${variantOf(route.key)},`,
    `        name: ${rustString(route.name)},`,
    `        category: Category::${CATEGORY_VARIANTS[route.category]},`,
    `        emoji: ${rustString(route.emoji)},`,
    `        description: ${rustString(route.description)},`,
    '        seo: Seo {',
    `            title: ${rustString(route.seo.title)},`,
    `            description: ${rustString(route.seo.description)},`,
    '        },',
    `        layout: Layout::${LAYOUT_VARIANTS[route.layout]},`,
    `        layout_opt_out_adr: ${route.layoutOptOutAdr === undefined ? 'None' : `Some(${rustString(route.layoutOptOutAdr)})`},`,
    '    },',
  ].join('\n')

export const renderRegistry = (routes: Array<ToolRoute>): string => {
  const variants = routes.map((route) => variantOf(route.key))
  const seen = new Set<string>()
  for (const variant of variants) {
    if (seen.has(variant)) throw new Error(`Two Tool keys make the variant ToolKey::${variant}`)
    seen.add(variant)
  }
  const count = routes.length

  return [
    HEADER,
    renderEnum('One variant per Tool, in `tool-routes.ts` order.', 'ToolKey', variants),
    '',
    `pub(crate) const KEYS: [&str; ${count}] = [`,
    ...routes.map((route) => `    ${rustString(route.key)},`),
    '];',
    '',
    renderEnum('A Tool category.', 'Category', Object.values(CATEGORY_VARIANTS)),
    '',
    renderAsStr('Category', CATEGORY_VARIANTS),
    '',
    renderEnum(
      'The layout shell a Tool is built from (`docs/ux/README.md`).',
      'Layout',
      Object.values(LAYOUT_VARIANTS),
    ),
    '',
    renderAsStr('Layout', LAYOUT_VARIANTS),
    '',
    '/// Every Tool, in `ToolKey` order.',
    `pub const TOOLS: [Tool; ${count}] = [`,
    ...routes.map(renderTool),
    '];',
    '',
  ].join('\n')
}
